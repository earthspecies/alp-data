"""Text-only LLM self-distillation dataset (capability restoration).

Prompt/response pairs generated by sampling from the raw base LLM
(``Qwen/Qwen3.5-9B``) across topics we care about — bioacoustics, animal
behavior, taxonomy, animal traits, ecology, and general knowledge. Used as a
post-training / joint-training signal to restore the base model's text,
world-knowledge, and reasoning abilities that are degraded by audio training.

Each row carries a pre-baked ``messages`` conversation (optional ``system``,
one or two user/assistant turns). For reasoning examples the assistant
``content`` keeps the full ``<think>…</think>`` block followed by the answer,
which the Qwen chat template re-parses at training time; the separated
``thinking`` and ``answer`` are also stored for convenience, alongside a
``reasoning`` flag and generation metadata.

There is no audio in this dataset.

Available splits
----------------
- ``train`` / ``val``: built by ``scripts/build_llm_text_distill.py`` and split
  deterministically by example id.
"""

from __future__ import annotations

import json
import logging
from typing import Any, Iterator

import polars as pl

from esp_data import Dataset, DatasetConfig, DatasetInfo, register_dataset
from esp_data.backends import BackendType
from esp_data.backends.polars_backend import PolarsBackend
from esp_data.io import AnyPathT, anypath, filesystem_from_path

logger = logging.getLogger(__name__)

_ROOT = "gs://foundation-model-data/synthetic/llm_text_distill/v0"


@register_dataset
class LLMTextDistill(Dataset):
    """Text-only prompt/response pairs distilled from the raw base LLM.

    Rows return a pre-baked ``messages`` conversation (no audio) plus metadata
    (``topic``, ``reasoning``, ``n_turns``, ``has_system``, split-out
    ``thinking``/``answer``, optional ``species`` grounding, and ``gen``
    parameters).

    Examples
    --------
    >>> from esp_data.datasets.llm_text_distill import LLMTextDistill
    >>> ds = LLMTextDistill(split="val")
    >>> row = ds[0]
    >>> row["messages"][-1]["role"]
    'assistant'
    """

    info = DatasetInfo(
        name="llm_text_distill",
        owner="david",
        split_paths={
            "train": f"{_ROOT}/train.jsonl",
            "val": f"{_ROOT}/val.jsonl",
        },
        version="0.1.0",
        description=(
            "Text-only self-distillation from the raw Qwen3.5-9B base LLM across "
            "bioacoustics, animal behavior, taxonomy, animal traits, ecology, and "
            "general knowledge. Prompts and responses both sampled from the base "
            "model; a mix of with/without reasoning, multi-turn, and system "
            "prompts. Used to restore text/reasoning abilities lost during audio "
            "training."
        ),
        sources=[_ROOT],
        license="internal",
    )

    _ALL_SPLITS = ("train", "val")

    def __init__(
        self,
        split: str = "train",
        output_take_and_give: dict[str, str] | None = None,
        data_root: str | AnyPathT | None = None,
        backend: BackendType = "polars",
        streaming: bool = False,
    ) -> None:
        """Initialize the LLMTextDistill dataset.

        Parameters
        ----------
        split : str
            One of ``train`` or ``val``.
        output_take_and_give : dict[str, str] | None
            Optional column rename mapping.
        data_root : str | AnyPathT | None
            Optional override for the directory holding ``{split}.jsonl`` (e.g.
            a ``v0_smoke`` build). When given, the manifest is read from
            ``{data_root}/{split}.jsonl`` instead of ``info.split_paths``.
        backend : BackendType
            Tabular backend (``"polars"`` or ``"pandas"``).
        streaming : bool
            Whether to use streaming mode.

        Raises
        ------
        LookupError
            If ``split`` is not one of the available splits.
        """
        super().__init__(output_take_and_give, backend=backend, streaming=streaming)
        if split not in self._ALL_SPLITS:
            raise LookupError(f"Invalid split: {split!r}. Expected one of {self._ALL_SPLITS}")
        self.split = split
        self.data_root = anypath(data_root) if data_root is not None else None
        self._data = None
        self._load()

    def _load(self) -> None:
        if self.data_root is not None:
            jsonl_path = f"{str(self.data_root).rstrip('/')}/{self.split}.jsonl"
        else:
            jsonl_path = self.info.split_paths[self.split]
        fs = filesystem_from_path(jsonl_path)
        records: list[dict[str, Any]] = []
        skipped = 0
        with fs.open(str(jsonl_path), "r") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError:
                    skipped += 1
        if skipped:
            logger.warning("Skipped %d malformed lines in %s", skipped, jsonl_path)
        self._data = PolarsBackend(pl.DataFrame(records))

    @property
    def columns(self) -> list[str]:
        return list(self._data.columns) if self._data is not None else []

    @property
    def available_splits(self) -> list[str]:
        return list(self._ALL_SPLITS)

    def _process(self, row: dict[str, Any]) -> dict[str, Any]:
        # Per-topic task labels give separate train/val logging buckets
        # (train/task/text_distill_<topic>/...); fall back to a flat label.
        topic = row.get("topic")
        row["task"] = f"text_distill_{topic}" if topic else row.get("task", "text_distill")
        if self.output_take_and_give:
            return {new: row[old] for old, new in self.output_take_and_give.items()}
        return row

    def __len__(self) -> int:
        if self._data is None:
            raise RuntimeError("No data loaded.")
        if self._streaming:
            raise NotImplementedError("Length not available in streaming mode.")
        return len(self._data)

    def __getitem__(self, idx: int) -> dict[str, Any]:
        return self._process(self._data[idx])

    def __iter__(self) -> Iterator[dict[str, Any]]:
        for row in self._data:
            yield self._process(row)

    @classmethod
    def from_config(cls, dataset_config: DatasetConfig) -> tuple["LLMTextDistill", dict[str, Any]]:
        cfg = dataset_config.model_dump(exclude={"dataset_name", "transformations"})
        ds = cls(
            split=cfg["split"],
            output_take_and_give=cfg["output_take_and_give"],
            data_root=cfg["data_root"],
            backend=cfg["backend"],
            streaming=cfg["streaming"],
        )
        if dataset_config.transformations:
            meta = ds.apply_transformations(dataset_config.transformations)
            return ds, meta
        return ds, {}

    def __str__(self) -> str:
        n = len(self) if self._data is not None and not self._streaming else "?"
        return (
            f"{self.info.name} (v{self.info.version}), split: {self.split}, {n} examples\n"
            f"Description: {self.info.description}\n"
            f"Available splits: {', '.join(self._ALL_SPLITS)}"
        )
